import test from 'node:test';
import assert from 'node:assert/strict';
import {createManuscriptScanSession,prepareManuscript,prepareBookBrowserPreview} from '../dist/index.js';
const rawScan=source=>({source,blocks:source.length?[{kind:'raw',range:{start:0,end:source.length}}]:[],diagnostics:[]});
const doc=(id,source,revision='1')=>({documentId:id,source,revision,startOn:'page'});
const content={width:100000,height:150000};
test('unchanged manuscripts skip scan and validation but global index sees new revisions',()=>{
  let scans=0,validations=0,indexes=0,seen=[];
  const deps={scan:source=>{scans++;return rawScan(source);},validate:parsed=>{validations++;return {diagnostics:parsed.diagnostics};},index:docs=>{indexes++;seen=docs.map(d=>[d.documentId,d.revision]);return {diagnostics:[]};}};
  const session=createManuscriptScanSession(),cached={...deps,scanSession:session};
  const before=[doc('a','本文。'),doc('b','説明。'),doc('c','まとめ。')];
  const run=(docs,revision)=>prepareBookBrowserPreview(docs,revision,'fixture',content,cached);
  assert.ok(run(before,'1').options);
  const next=[doc('a','本文。','2'),doc('b','変更。','2'),doc('c','まとめ。','2')];
  const actual=run(next,'2');
  assert.equal(scans,4);assert.equal(validations,4);assert.equal(indexes,2);
  assert.deepEqual(seen,[['a','2'],['b','2'],['c','2']]);
  assert.equal(session.stats().hits,2);
  assert.deepEqual(actual,prepareBookBrowserPreview(next,'2','fixture',content,deps));
});
test('cache is isolated from caller mutations, handles same-revision changes and service replacement',()=>{
  const session=createManuscriptScanSession(),validate=parsed=>({diagnostics:parsed.diagnostics});
  const a=session.read('a','abc',rawScan,validate);
  a.parsed.blocks[0].range.end=99;
  const b=session.read('a','abc',rawScan,validate);
  assert.equal(b.parsed.blocks[0].range.end,3);
  b.parsed.blocks.length=0;
  assert.equal(session.read('a','abc',rawScan,validate).parsed.blocks.length,1);
  assert.equal(session.read('a','abcd',rawScan,validate).parsed.source,'abcd');
  session.read('a','abcd',source=>rawScan(source),validate);
  assert.equal(session.stats().hits,0);
  assert.equal(session.stats().misses,1);
  session.clear();
  assert.deepEqual(session.stats(),{entries:0,characters:0,hits:0,misses:0});
});
test('validation failures and global index conflicts never become accepted',()=>{
  const session=createManuscriptScanSession();
  const scan=rawScan;
  const validate=parsed=>({diagnostics:parsed.source==='bad'?[{code:'INVALID',range:{start:0,end:3},message:'invalid'}]:[]});
  let conflict=false;
  const deps={scan,validate,index:()=>({diagnostics:conflict?[{code:'DUPLICATE',occurrence:{documentId:'a',range:{start:0,end:2}}}]:[]}),scanSession:session};
  const run=docs=>prepareManuscript(docs,'1','fixture',content,deps);
  assert.equal(run([doc('a','bad')]).diagnostics[0].code,'INVALID');
  assert.equal(run([doc('a','bad')]).diagnostics[0].code,'INVALID');
  assert.equal(session.stats().hits,1);
  assert.ok(run([doc('a','本文。')]).input);
  conflict=true;
  assert.equal(run([doc('a','本文。')]).diagnostics[0].code,'DUPLICATE');
});
test('session bounds and non-cloneable scan extensions bypass retention',()=>{
  const session=createManuscriptScanSession(),validate=()=>({diagnostics:[]});
  for(let i=0;i<70;i++)session.read(String(i),'abc',rawScan,validate);
  assert.equal(session.stats().entries,64);
  session.read('large','x'.repeat(250001),rawScan,validate);
  assert.ok(session.stats().characters<=250000);
  const extended=source=>({...rawScan(source),callback:()=>{}});
  session.read('x','abc',extended,validate);
  assert.equal(session.stats().entries,0);
  session.read('x','abc',extended,validate);
  assert.equal(session.stats().misses,2);
});
