import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createProject,openWorkspace} from '../workspace.mjs';
import {defaultHeadingDesign} from '../../../dist/index.js';
test('library CRUD, revision guard, reopen and independent applied copy',async t=>{
  const root=await mkdtemp(join(tmpdir(),'bc-library-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const ws=await createProject(root,{title:'Library test',folder:'book',size:'A5'}),initial=await ws.typography();
  assert.equal(initial.libraryEditable,true);assert.deepEqual(initial.library.entries,[]);
  const design=defaultHeadingDesign();
  const added=await ws.changeComponentLibrary(initial.revision,{type:'add',name:'章見出し',design});
  const id=added.library.entries[0].id;
  assert.equal(added.headingDesign,null);
  await assert.rejects(ws.changeComponentLibrary(initial.revision,{type:'rename',id,name:'古い変更'}),/changed/);
  await assert.rejects(ws.changeComponentLibrary(added.revision,{type:'add',name:'章見出し',design}),/Duplicate/);
  const applied=await ws.saveHeadingDesign(added.revision,added.library.entries[0].design,'2');
  const renamed=await ws.changeComponentLibrary(applied.revision,{type:'rename',id,name:'別名'});
  const replacement={...design,background:'#abcdef'};
  const replaced=await ws.changeComponentLibrary(renamed.revision,{type:'replace',id,design:replacement});
  assert.equal(replaced.library.entries[0].id,id);
  assert.deepEqual(replaced.headingLevels['2'],design);
  const reopened=await openWorkspace(join(root,'book','book.yaml')),saved=await reopened.typography();
  assert.deepEqual(saved.library.entries,[{id,name:'別名',usage:'heading',design:replacement}]);
  const deleted=await reopened.changeComponentLibrary(saved.revision,{type:'delete',id});
  assert.deepEqual(deleted.library.entries,[]);
  assert.deepEqual(deleted.headingLevels['2'],design);
  const themePath=join(root,'book','themes','default','theme.yaml');
  const raw=await readFile(themePath,'utf8');await writeFile(themePath,raw.replace(/previewComponentLibrary:\s*\n\s*schemaVersion: 1/,'previewComponentLibrary:\n  schemaVersion: 99'));
  const invalid=await reopened.typography();assert.equal(invalid.libraryEditable,false);assert.equal(invalid.componentEditable,true);
});
