import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createProject,openWorkspace} from '../workspace.mjs';
import {defaultHeadingDesign} from '../../../dist/index.js';
test('shared binding propagates replacement, preserves independent copy and blocks deletion',async t=>{
  const root=await mkdtemp(join(tmpdir(),'bc-shared-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const ws=await createProject(root,{title:'Shared test',folder:'book',size:'A5'});
  const design=defaultHeadingDesign(),initial=await ws.typography();
  const added=await ws.changeComponentLibrary(initial.revision,{type:'add',name:'Shared',design});
  const id=added.library.entries[0].id;
  const bound=await ws.saveHeadingDesign(added.revision,{componentId:id},'default');
  const two=await ws.saveHeadingDesign(bound.revision,{componentId:id},'2');
  const local=await ws.saveHeadingDesign(two.revision,design,'3');
  assert.deepEqual(local.bindings,{default:id,'2':id});
  assert.deepEqual(local.headingDesign,design);
  await assert.rejects(ws.changeComponentLibrary(local.revision,{type:'delete',id}),/referenced/);
  await assert.rejects(ws.saveHeadingDesign(local.revision,{componentId:'component-00000000-0000-4000-8000-000000000009'},'4'),/Missing/);
  const replacement={...design,background:'#abcdef'};
  const changed=await ws.changeComponentLibrary(local.revision,{type:'replace',id,design:replacement});
  assert.deepEqual(changed.headingDesign,replacement);assert.deepEqual(changed.headingLevels['2'],replacement);assert.deepEqual(changed.headingLevels['3'],design);
  const reopened=await openWorkspace(join(root,'book','book.yaml')),saved=await reopened.typography();
  assert.deepEqual(saved.bindings,changed.bindings);assert.deepEqual(saved.headingDesign,replacement);
  const copy=await reopened.saveHeadingDesign(saved.revision,saved.headingDesign,'default');
  const unbound=await reopened.saveHeadingDesign(copy.revision,null,'2');
  assert.deepEqual(unbound.bindings,{});assert.deepEqual(unbound.headingDesign,replacement);assert.equal(unbound.headingLevels['2'],undefined);
  const deleted=await reopened.changeComponentLibrary(unbound.revision,{type:'delete',id});
  assert.deepEqual(deleted.library.entries,[]);assert.deepEqual(deleted.headingLevels['3'],design);
  const yaml=await readFile(join(root,'book','themes','default','theme.yaml'),'utf8');
  assert.match(yaml,/previewComponents:\s*\n\s*schemaVersion: 2/);
});
