import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createManuscriptStore} from '../manuscript-store.mjs';
import {planStructuredCommit,planStructuredHistoryMove} from '../manuscript-state.mjs';
const file=(id='a')=>({id,text:'原稿',editable:true,revision:'r1'});
test('100 source edits notify the source but only the first dirty transition reaches metadata',()=>{
  const store=createManuscriptStore();
  store.dispatch({type:'install',file:file()});
  let source=0,metadata=0,full=0;
  store.subscribeSource(()=>source++);
  store.subscribeMetadata(()=>metadata++);
  store.subscribe(()=>full++);
  const original=store.getMetadata();
  for(let i=0;i<100;i++)store.dispatch({type:'edit',value:String(i)});
  assert.equal(source,100);assert.equal(metadata,1);assert.equal(full,100);
  assert.notEqual(store.getMetadata(),original);
  assert.equal(store.getSource().value,'99');
  const snapshot=store.getSnapshot();
  store.dispatch({type:'edit',value:'99'});
  assert.equal(store.getSnapshot(),snapshot);
  assert.equal(source,100);
});
test('save updates metadata without replacing newer source and subscribers see atomic snapshots',()=>{
  const store=createManuscriptStore();
  const first=file();
  store.dispatch({type:'install',file:first});
  store.dispatch({type:'edit',value:'追記'});
  const pending=store.getSnapshot();
  store.dispatch({type:'edit',value:'追記2'});
  const source=store.getSource();
  let calls=0;
  store.subscribeSource(()=>calls++);
  let observed=false;
  store.subscribeMetadata(()=>{
    observed=true;
    assert.equal(store.getSnapshot().file,store.getMetadata().file);
    assert.equal(store.getSnapshot().text,store.getSource().value);
  });
  store.dispatch({type:'saved',file:pending.file,value:pending.text,revision:'r2'});
  assert.equal(store.getSource(),source);assert.equal(calls,0);assert.equal(observed,true);
  assert.equal(store.getMetadata().file.text,'追記');assert.equal(store.getMetadata().dirty,true);
  store.dispatch({type:'install',file:file('b')});
  const current=store.getSnapshot();
  store.dispatch({type:'saved',file:first,value:'stale',revision:'r3'});
  assert.equal(store.getSnapshot(),current);
});
test('history, editable, clearing, unsubscribe and workspace isolation',()=>{
  const a=createManuscriptStore(),b=createManuscriptStore();
  a.dispatch({type:'install',file:file()});
  let n=0;const stop=a.subscribeSource(()=>n++);
  a.dispatch({type:'edit',value:'B',history:planStructuredCommit(a.getSnapshot(),'B')});
  assert.equal(a.getMetadata().undo,true);
  const history=planStructuredHistoryMove(a.getSnapshot(),'undo');
  a.dispatch({type:'edit',value:history.current,history});
  assert.equal(a.getMetadata().redo,true);assert.equal(a.getMetadata().dirty,false);
  a.dispatch({type:'editable',editable:false});assert.equal(a.getSource().editable,false);
  assert.equal(n,3);stop();
  a.dispatch({type:'clear'});
  assert.equal(n,3);assert.equal(a.getSource().hasFile,false);assert.equal(b.getSnapshot().file,null);
});

test('workspace metadata stays stable across a sustained dirty typing burst while both editor projections stay current',()=>{
  const store=createManuscriptStore();
  store.dispatch({type:'install',file:file()});
  store.dispatch({type:'edit',value:'first edit'});
  const workspace=store.getMetadata();
  let workspaceNotifications=0,editorNotifications=0,previewNotifications=0;
  store.subscribeMetadata(()=>workspaceNotifications++);
  store.subscribeSource(()=>editorNotifications++);
  store.subscribePreviewInput(()=>previewNotifications++);
  for(let i=0;i<100;i++)store.dispatch({type:'edit',value:'first edit '+i});
  assert.equal(workspaceNotifications,0);
  assert.equal(editorNotifications,100);
  assert.equal(previewNotifications,100);
  assert.equal(store.getMetadata(),workspace);
  assert.equal(store.getSource().value,'first edit 99');
  assert.equal(store.getPreviewInput().text,'first edit 99');
  const pending=store.getSnapshot();
  store.dispatch({type:'saved',file:pending.file,value:pending.text,revision:'r2'});
  assert.equal(workspaceNotifications,1);
  assert.equal(editorNotifications,100);
  assert.equal(store.getMetadata().dirty,false);
});
