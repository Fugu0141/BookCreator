import test from 'node:test';
import assert from 'node:assert/strict';
import {assertMatchingPrintPlan} from '../trial-print-plan.mjs';
import {renderTrialPdfInWindow,TRIAL_PRINT_PAGE} from '../trial-print-window.mjs';
const plan={revision:'1',fingerprint:'book',completeness:'full',publicationReady:false,pages:[{index:0,fragments:[{origin:{documentId:'chapter',revision:'1',blockKey:'a',range:{start:0,end:8}},rect:{x:0,y:0,width:100000,height:5000},unitStart:0,unitEnd:1,continuationIndex:0,breakReason:'flow'}]}],diagnostics:[]};
const options={revision:'1',fingerprint:'book',paper:{width:148000,height:210000},sections:[]};
test('print plan must match all physical positions and source ranges',()=>{
  assert.doesNotThrow(()=>assertMatchingPrintPlan(plan,structuredClone(plan)));
  for(const change of [p=>p.pages[0].fragments[0].rect.x++,p=>p.pages[0].fragments[0].origin.range.end++,p=>p.pages[0].fragments[0].unitEnd++,p=>p.fingerprint='stale',p=>p.completeness='partial',p=>p.diagnostics.push({severity:'error'})]){
    const copy=structuredClone(plan);change(copy);assert.throws(()=>assertMatchingPrintPlan(plan,copy));
  }
});
function harness({report={pageCount:1,revision:'1',fingerprint:'book',publicationReady:false},afterPrint=()=>{}}={}){
  const calls=[];
  class Window{
    constructor(config){calls.push(['create',config]);this.webContents={setWindowOpenHandler:()=>{},on:()=>{},getURL:()=>TRIAL_PRINT_PAGE,executeJavaScript:async code=>{calls.push(['render',code]);return report;},printToPDF:async config=>{calls.push(['print',config]);afterPrint();return Buffer.from('fixture');}};}
    async loadURL(url){calls.push(['load',url]);}
    isDestroyed(){return false;}
    destroy(){calls.push(['destroy']);}
  }
  return {calls,run:isCurrent=>renderTrialPdfInWindow({BrowserWindow:Window,options,expectedPlan:plan,isCurrent})};
}
test('hidden sandboxed print window is destroyed after PDF generation',async()=>{
  const h=harness();const result=await h.run(()=>true);
  assert.equal(result.bytes.toString(),'fixture');
  assert.equal(result.report.pageCount,1);
  assert.equal(h.calls[0][1].show,false);
  assert.equal(h.calls[0][1].webPreferences.sandbox,true);
  assert.equal(h.calls[0][1].webPreferences.preload,undefined);
  assert.deepEqual(h.calls.find(c=>c[0]==='print')[1],{printBackground:true,displayHeaderFooter:false,preferCSSPageSize:true,scale:1});
  assert.equal(h.calls.at(-1)[0],'destroy');
});
test('wrong page report prevents printing and closes the window',async()=>{
  const h=harness({report:{pageCount:2,revision:'1',fingerprint:'book',publicationReady:false}});
  await assert.rejects(h.run(()=>true),/検査/);
  assert.equal(h.calls.some(c=>c[0]==='print'),false);
  assert.equal(h.calls.at(-1)[0],'destroy');
});
test('stale input after Chromium print discards generated bytes',async()=>{
  let current=true;const h=harness({afterPrint:()=>{current=false;}});
  await assert.rejects(h.run(()=>current),/更新/);
  assert.equal(h.calls.at(-1)[0],'destroy');
});
