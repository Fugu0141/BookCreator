import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createProject,openWorkspace} from '../workspace.mjs';
import {defaultStudyDesign,defaultHeadingDesign} from '../../../dist/index.js';
test('study kind bindings persist and propagate, independent copies detach safely',async t=>{
  const root=await mkdtemp(join(tmpdir(),'bc-study-lib-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const ws=await createProject(root,{title:'Study library',folder:'book',size:'A5'});
  const initial=await ws.typography(),design=defaultStudyDesign('example');
  const h=await ws.changeComponentLibrary(initial.revision,{type:'add',name:'Heading',design:defaultHeadingDesign()});
  const added=await ws.changeComponentLibrary(h.revision,{type:'add',usage:'study',name:'Study',design});
  const id=added.library.entries[1].id,hid=added.library.entries[0].id;
  assert.equal(added.library.schemaVersion,3);
  await assert.rejects(ws.saveStudyDesign(added.revision,{componentId:hid},'warning'),/usage/);
  await assert.rejects(ws.saveHeadingDesign(added.revision,{componentId:id},'1'),/usage/);
  const a=await ws.saveStudyDesign(added.revision,{componentId:id},'example');
  const b=await ws.saveStudyDesign(a.revision,{componentId:id},'warning');
  await assert.rejects(ws.changeComponentLibrary(b.revision,{type:'delete',id}),/referenced/);
  const replacement={...design,padding:5000};
  const c=await ws.changeComponentLibrary(b.revision,{type:'replace',id,design:replacement});
  assert.deepEqual(c.studyDesigns,{example:replacement,warning:replacement});
  const reopened=await openWorkspace(join(root,'book','book.yaml')),saved=await reopened.typography();
  assert.deepEqual(saved.studyBindings,{example:id,warning:id});
  const copy=await reopened.saveStudyDesign(saved.revision,saved.studyDesigns.warning,'warning');
  const reset=await reopened.saveStudyDesign(copy.revision,null,'example');
  const deleted=await reopened.changeComponentLibrary(reset.revision,{type:'delete',id});
  assert.deepEqual(deleted.studyBindings,{});assert.deepEqual(deleted.studyDesigns,{warning:replacement});
  assert.equal(deleted.library.schemaVersion,1);
});
