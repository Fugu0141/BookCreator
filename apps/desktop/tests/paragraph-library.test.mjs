import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createProject,openWorkspace} from '../workspace.mjs';
import {defaultParagraphDesign,defaultHeadingDesign} from '../../../dist/index.js';
test('mixed library, typed bindings, shared paragraph updates and independent copy',async t=>{
  const root=await mkdtemp(join(tmpdir(),'bc-para-lib-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const ws=await createProject(root,{title:'Typed library',folder:'book',size:'A5'});
  const d=defaultParagraphDesign(),h=defaultHeadingDesign(),initial=await ws.typography();
  const heading=await ws.changeComponentLibrary(initial.revision,{type:'add',name:'Heading',design:h}),hid=heading.library.entries[0].id;
  const mixed=await ws.changeComponentLibrary(heading.revision,{type:'add',usage:'paragraph',name:'本文',design:d}),pid=mixed.library.entries[1].id;
  assert.equal(mixed.library.schemaVersion,2);
  await assert.rejects(ws.saveHeadingDesign(mixed.revision,{componentId:pid},'1'),/usage/);
  await assert.rejects(ws.saveParagraphDesign(mixed.revision,{componentId:hid}),/usage/);
  await assert.rejects(ws.changeComponentLibrary(mixed.revision,{type:'replace',id:pid,design:h}),/single content slot/);
  const hb=await ws.saveHeadingDesign(mixed.revision,{componentId:hid},'1');
  const pb=await ws.saveParagraphDesign(hb.revision,{componentId:pid});
  assert.equal(pb.paragraphBinding,pid);assert.deepEqual(pb.paragraphDesign,d);
  await assert.rejects(ws.changeComponentLibrary(pb.revision,{type:'delete',id:pid}),/referenced/);
  const next={...d,padding:4000,background:'#abcdef'};
  const replaced=await ws.changeComponentLibrary(pb.revision,{type:'replace',id:pid,design:next});
  assert.deepEqual(replaced.paragraphDesign,next);assert.deepEqual(replaced.headingLevels['1'],h);
  const reopened=await openWorkspace(join(root,'book','book.yaml')),saved=await reopened.typography();
  assert.equal(saved.paragraphBinding,pid);assert.deepEqual(saved.paragraphDesign,next);
  const copy=await reopened.saveParagraphDesign(saved.revision,saved.paragraphDesign);
  assert.equal(copy.paragraphBinding,null);
  const deleted=await reopened.changeComponentLibrary(copy.revision,{type:'delete',id:pid});
  assert.equal(deleted.library.schemaVersion,1);assert.deepEqual(deleted.paragraphDesign,next);
  assert.equal(deleted.bindings['1'],hid);
  const raw=await readFile(join(root,'book','themes','default','theme.yaml'),'utf8');
  assert.match(raw,/previewParagraph:\s*\n\s*schemaVersion: 1/);
});
